export interface Course {
  /** Código de la asignatura (id único) */
  id: string
  /** Asignatura real de la malla */
  subject: string
  /** Nombre del logro estilo Minecraft */
  achievement: string
  /** Motivo / descripción del logro */
  description: string
  /** Semestre (1..11) */
  semester: number
  /** Créditos */
  credits: number
  /** Área académica */
  area: CourseArea
  /** Prerrequisitos (códigos) */
  prereqs: string[]
  /** Nombre del icono lucide */
  icon: string
  /** Estilo del marco */
  type: CourseType
}

